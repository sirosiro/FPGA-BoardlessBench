#!/usr/bin/env python3
"""
@file scripts/vfpga/emitter_gtr.py
@intent:responsibility
    Device および Register モデルから、Linux Device Tree 標準の config.dts
    および仮想ハードウェア契約 config.gtr を二層分離形式で生成・出力する。
@intent:rationale
    F-BB の GTR 二層分離アーキテクチャ（ADR #015）に厳格に準拠し、
    人間が手書きしたかのような清潔で規格準拠の DTS / GTR ソースコードを生成する。
"""

import os
from typing import List
from vfpga.models import Device


class GtrEmitter:
    """
    Device モデルから config.dts および config.gtr を生成するエミッタークラス
    """

    @staticmethod
    def emit_dts(devices: List[Device]) -> str:
        """
        100% Upstream Linux 準拠の config.dts ソースコードを生成する
        """
        lines = [
            "/dts-v1/;",
            "",
            "/*",
            " * Auto-generated by F-BB Hardware Importer",
            " * Linux Upstream-Compliant Device Tree (config.dts)",
            " * Hardware Topology Definition (Compatible with Vivado / PetaLinux / Yocto)",
            " */",
            "",
            "/ {",
        ]

        for dev in devices:
            base_hex = f"0x{dev.base_addr:08x}"
            size_hex = f"0x{dev.size:x}" if dev.size > 0 else "0x1000"
            node_name = f"{dev.name}@{dev.base_addr:08x}"

            lines.append(f"    {dev.name}: {node_name} {{")
            lines.append("        compatible = \"generic-uio\";")
            lines.append(f"        reg = <{base_hex} {size_hex}>;")
            lines.append(f"        label = \"{dev.path}\";")
            lines.append("        status = \"okay\";")
            lines.append("    };")
            lines.append("")

        lines.append("};")
        lines.append("")
        return "\n".join(lines)

    @staticmethod
    def emit_gtr(devices: List[Device]) -> str:
        """
        F-BB シミュレータ用の仮想レジスタ契約 config.gtr を生成する
        """
        lines = [
            "/dts-v1/;",
            "",
            "/*",
            " * Auto-generated by F-BB Hardware Importer",
            " * General Tree Registers (config.gtr)",
            " * Virtual Hardware Register Contract for F-BB Simulation",
            " */",
            "",
            "/include/ \"config.dts\"",
            "",
        ]

        for dev in devices:
            if not dev.registers:
                continue

            lines.append(f"&{dev.name} {{")
            lines.append("    registers =")

            reg_count = len(dev.registers)
            for idx, reg in enumerate(dev.registers):
                is_last = (idx == reg_count - 1)
                comma_semicolon = ";" if is_last else ","
                dir_spec = f" : {reg.direction}" if reg.direction in ["RO", "WO", "RW"] else ""
                lines.append(f'        "{reg.name} @ {reg.offset}{dir_spec}"{comma_semicolon}')

            lines.append("};")
            lines.append("")

        return "\n".join(lines)

    @classmethod
    def write_scenario_pair(cls, devices: List[Device], output_dir: str):
        """
        指定されたディレクトリに config.dts と config.gtr を書き出す
        """
        os.makedirs(output_dir, exist_ok=True)
        dts_content = cls.emit_dts(devices)
        gtr_content = cls.emit_gtr(devices)

        dts_path = os.path.join(output_dir, "config.dts")
        gtr_path = os.path.join(output_dir, "config.gtr")

        with open(dts_path, "w", encoding="utf-8") as f:
            f.write(dts_content)

        with open(gtr_path, "w", encoding="utf-8") as f:
            f.write(gtr_content)

        return dts_path, gtr_path

